// metricflow is an emit-only target that writes a dbt project fragment
// MetricFlow can actually run, as opposed to the `dbt` target, whose output is
// shaped for a lossless dbt -> IR -> dbt round-trip. The differences:
//
//   - Entities are named after the table they identify (primary) or point at
//     (foreign), not after physical columns. Two role-playing tables over the
//     same physical table (customer_nation, supplier_nation) therefore get
//     distinct entities instead of colliding on `n_nationkey`.
//   - Every relationship becomes a foreign entity, which is how MetricFlow
//     discovers joins (a `relationships` data test is invisible to it).
//   - A composite key becomes ONE entity whose expr concatenates the key
//     columns, on both sides of the join, since MetricFlow entities are
//     single-valued and a semantic model may have only one primary entity.
//   - Time dimensions carry `type_params.time_granularity`, and a semantic model
//     with measures gets `defaults.agg_time_dimension` (its declared grain, else
//     its first time dimension). A model with measures but no time dimension is
//     reported: MetricFlow requires an aggregation time dimension per measure.
//   - Because a dbt schema file has no slot for a physical table, each table's
//     ir.Table.Source is written as a `models/<table>.sql` (select * from it),
//     and a `metricflow_time_spine` model is added.
type metricflow struct{ opts Options }

func init() { Register(metricflow{}) }

func (metricflow) Name() string { return "metricflow" }

// WithOptions lets the CLI pass the profile's identity fields.
func (metricflow) WithOptions(o Options) Emitter { return metricflow{opts: o} }

// mfKeySep separates key parts in a concatenated composite-key entity.
const mfKeySep = "'|'"

// mfKeyExpr renders the entity expression for an ordered list of key columns:
// the bare column for a single key, else a typed concatenation.
func mfKeyExpr(cols []string) string {
	if len(cols) == 1 {
		return cols[0]
	}
	parts := make([]string, len(cols))
	for i, c := range cols {
		parts[i] = "CAST(" + c + " AS VARCHAR)"
	}
	return strings.Join(parts, " || "+mfKeySep+" || ")
}

func (e metricflow) Emit(m *ir.Model, dir string) ([]string, error) {
	f, warnings := buildDBTFile(m, true)
	// The physical-source warnings buildDBTFile raises do not apply here: this
	// target writes each source into a model SQL file below.
	kept := warnings[:0]
	for _, w := range warnings {
		if strings.Contains(w, "has no slot for a table's physical address") {
			continue
		}
		kept = append(kept, w)
	}
	warnings = kept

	name := e.opts.Name
	if name == "" {
		name = "semantic_layer"
	}
	modelsDir := filepath.Join(dir, "models")
	if err := os.MkdirAll(modelsDir, 0o755); err != nil {
		return warnings, err
	}
	for _, t := range m.Tables {
		src := t.Source
		if src == "" {
			src = t.Name
			warnings = append(warnings, fmt.Sprintf(
				"table %q has no physical source; models/%s.sql selects from %q, edit it to point at the real table", t.Name, t.Name, t.Name))
		}
		sql := fmt.Sprintf("-- generated by semglot (metricflow target)\nselect * from %s\n", src)
		if err := os.WriteFile(filepath.Join(modelsDir, t.Name+".sql"), []byte(sql), 0o644); err != nil {
			return warnings, err
		}
	}
	spine := `-- generated by semglot (metricflow target): daily time spine
with recursive d (date_day) as (
    select cast('1990-01-01' as date)
    union all
    select cast(date_day + interval '1' day as date) from d where date_day < cast('2005-12-31' as date)
)
select date_day from d
`
	if err := os.WriteFile(filepath.Join(modelsDir, "metricflow_time_spine.sql"), []byte(spine), 0o644); err != nil {
		return warnings, err
	}
	out := struct {
		dbtEmitFile `yaml:",inline"`
	}{f}
	if err := writeDBTFile(out, modelsDir, name+".yml"); err != nil {
		return warnings, err
	}
	spineYAML := map[string]any{"models": []map[string]any{{
		"name":       "metricflow_time_spine",
		"time_spine": map[string]any{"standard_granularity_column": "date_day"},
		"columns":    []map[string]any{{"name": "date_day", "granularity": "day"}},
	}}}
	return warnings, writeDBTFile(spineYAML, modelsDir, "metricflow_time_spine.yml")
}

// emitSemanticMF builds a MetricFlow-runnable semantic model for t (see the
// metricflow type for the rules).
func emitSemanticMF(m *ir.Model, t ir.Table, pk, fk map[string]bool) (dbtEmitSemantic, []string) {
	var warnings []string
	sm := dbtEmitSemantic{Name: t.Name, Model: "ref('" + t.Name + "')"}

	if len(t.PrimaryKey) > 0 {
		sm.Entities = append(sm.Entities, dbtEmitEntity{
			Name: t.Name, Type: "primary", Expr: mfKeyExpr(t.PrimaryKey),
		})
	}
	tables := map[string]ir.Table{}
	for _, x := range m.Tables {
		tables[x.Name] = x
	}
	used := map[string]bool{t.Name: true}
	for _, r := range m.Relationships {
		if r.Left != t.Name || len(r.Columns) == 0 {
			continue
		}
		right, ok := tables[r.Right]
		if !ok {
			continue
		}
		// Order the FK columns by the target's primary key so both sides of a
		// composite key concatenate in the same order.
		byRight := map[string]string{}
		for _, cp := range r.Columns {
			byRight[cp.Right] = cp.Left
		}
		var cols []string
		for _, k := range right.PrimaryKey {
			if c, ok := byRight[k]; ok {
				cols = append(cols, c)
			}
		}
		if len(cols) != len(r.Columns) || len(cols) != len(right.PrimaryKey) {
			warnings = append(warnings, fmt.Sprintf(
				"relationship %s -> %s not emitted as a MetricFlow entity: its columns are not exactly %q's primary key",
				r.Left, r.Right, r.Right))
			continue
		}
		name := r.Right
		if used[name] {
			// A second join to the same table (a role-playing FK). Generate the
			// entity name from the FK columns rather than trusting a declared
			// relationship name, which may be duplicated or illegal.
			name = r.Right + "_via_" + strings.Join(cols, "_")
			if used[name] || !isIdent(name) {
				warnings = append(warnings, fmt.Sprintf(
					"relationship %s -> %s not emitted: no distinct entity name for a second join to the same table", r.Left, r.Right))
				continue
			}
			warnings = append(warnings, fmt.Sprintf(
				"relationship %s -> %s emitted as entity %q (a second join to the same table); queries reach it as %s__<dimension>",
				r.Left, r.Right, name, name))
		}
		used[name] = true
		sm.Entities = append(sm.Entities, dbtEmitEntity{Name: name, Type: "foreign", Expr: mfKeyExpr(cols)})
	}

	for _, d := range t.Dimensions {
		if pk[d.Expr] || fk[d.Expr] || used[d.Name] {
			continue
		}
		sm.Dimensions = append(sm.Dimensions, dbtEmitDimension{
			Name: d.Name, Type: "categorical", Expr: exprIfDiffers(d.Name, d.Expr),
		})
	}
	for _, d := range t.TimeDimensions {
		sm.Dimensions = append(sm.Dimensions, dbtEmitDimension{
			Name: d.Name, Type: "time", Expr: exprIfDiffers(d.Name, d.Expr),
			TypeParams: &dbtEmitDimTypeParams{TimeGranularity: "day"},
		})
	}
	for _, ms := range t.Measures {
		sm.Measures = append(sm.Measures, dbtEmitMeasure{Name: ms.Name, Agg: mfAgg(ms.Agg), Expr: mfUnqualify(ms.Expr, t.Name)})
	}
	grain := t.Grain
	if grain == "" && len(t.TimeDimensions) > 0 {
		grain = t.TimeDimensions[0].Name
	}
	if len(sm.Measures) > 0 && grain != "" {
		sm.Defaults = &dbtEmitDefaults{AggTimeDimension: grain}
	}
	return sm, warnings
}

// mfAgg maps an IR aggregation name to MetricFlow's AggregationType spelling
// (MetricFlow says `average`, where SQL-derived sources say `avg`).
func mfAgg(a string) string {
	switch strings.ToLower(a) {
	case "avg", "mean":
		return "average"
	case "countdistinct", "distinct_count":
		return "count_distinct"
	}
	return strings.ToLower(a)
}

// mfUnqualify strips the owning table's own qualifier from an expression
// ("lineitem.l_discount" -> "l_discount"). MetricFlow aliases each semantic
// model's table in the SQL it generates, so a measure expression must refer to
// its columns unqualified.
func mfUnqualify(expr, table string) string {
	re := regexp.MustCompile(`(?i)\b` + regexp.QuoteMeta(table) + `\.`)
	return re.ReplaceAllString(expr, "")
}
